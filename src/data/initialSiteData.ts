import { TelecomSite, Port, ConnectorType } from '../types/telecom';

function createPorts(
  prefix: string,
  count: number,
  connector: ConnectorType,
  role: 'front_patch' | 'rear_trunk' | 'transceiver',
  wavelengthNm = 1310,
  isPatchPanel = true
): Port[] {
  const ports: Port[] = [];
  for (let i = 1; i <= count; i++) {
    const numStr = String(i).padStart(2, '0');
    const portId = `${prefix}-P${numStr}`;
    ports.push({
      id: portId,
      number: i,
      label: `Port ${numStr}`,
      connector,
      status: 'free',
      role,
      wavelengthNm,
      txPowerDbm: role === 'transceiver' ? 2.0 : undefined,
      rxSensitivityDbm: role === 'transceiver' ? -14.0 : undefined,
      pairedInternalPortId: isPatchPanel ? `${prefix}-REAR-P${numStr}` : undefined,
      customAttributes: [
        {
          id: `${portId}-attr1`,
          key: 'Fibre & Polissage',
          value: `OS2 Monomode 9/125µm · ${connector.includes('APC') ? 'APC 8° (Vert)' : 'UPC 0° (Bleu)'}`,
        },
        { id: `${portId}-attr2`, key: 'Longueur d\'onde', value: `${wavelengthNm} nm` },
      ],
    });
  }
  return ports;
}

