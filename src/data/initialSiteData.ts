// Synchronize initial port statuses with initial fibers
export function syncSitePortStatuses(site: TelecomSite): TelecomSite {
  const updatedEquipments = site.equipments.map((eq) => ({
    ...eq,
    ports: eq.ports.map((port) => {
      const connectedFiber = site.fibers.find(
        (f) =>
          (f.sourceEquipmentId === eq.id && f.sourcePortId === port.id) ||
          (f.targetEquipmentId === eq.id && f.targetPortId === port.id)
      );
      return {
        ...port,
        status: connectedFiber ? ('connected' as const) : port.status === 'connected' ? ('free' as const) : port.status,
        connectedFiberId: connectedFiber ? connectedFiber.id : undefined,
      };
    }),
  }));

  return {
    ...site,
    equipments: updatedEquipments,
  };
}
